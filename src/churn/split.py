"""Split the raw data into a training set and an untouched test set.

Run once from the project root:
    python -m churn.split
"""

import argparse
import logging
from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

from churn.config import (
    POSITIVE_LABEL,
    RANDOM_STATE,
    TARGET_COLUMN,
    TEST_PATH,
    TEST_SIZE,
    TRAIN_PATH,
)
from churn.data import load_raw_data

# A logger for this file. Used instead of print(), so messages have a level
# (INFO, WARNING, ERROR) and can be turned off or saved to a file later.
logger = logging.getLogger(__name__)


# Split customers 80/20 into train and test, with the same churn rate in both.
def split_train_test(
    df: pd.DataFrame,
    test_size: float = TEST_SIZE,
    random_state: int = RANDOM_STATE,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Split customers into train and test sets, keeping the churn rate equal.

    Args:
        df: The full dataset, one row per customer.
        test_size: Share of customers to put in the test set (0 to 1).
        random_state: Seed, so the same split is produced every run.

    Returns:
        The training set and the test set, in that order.

    Raises:
        ValueError: If test_size is not between 0 and 1.
    """
    # Guard clause: a test size like 0 or 1.5 makes no sense.
    if not 0 < test_size < 1:
        raise ValueError(f"test_size must be between 0 and 1, got {test_size}.")

    # stratify=Churn keeps about 28.8% churners in BOTH sets.
    # random_state fixes the shuffle, so the split is the same every run.
    train_df, test_df = train_test_split(
        df,
        test_size=test_size,
        random_state=random_state,
        stratify=df[TARGET_COLUMN],
    )
    return train_df, test_df


# Save train and test as CSV files. Refuses to replace existing files,
# so the test set cannot be changed by accident.
def save_splits(
    train_df: pd.DataFrame,
    test_df: pd.DataFrame,
    train_path: Path = TRAIN_PATH,
    test_path: Path = TEST_PATH,
    overwrite: bool = False,
) -> None:
    """Save the train and test sets as CSV files.

    Args:
        train_df: The training set.
        test_df: The test set.
        train_path: Where to save the training set.
        test_path: Where to save the test set.
        overwrite: Replace existing files. False by default to protect the
            test set from being regenerated by accident.

    Raises:
        FileExistsError: If a file already exists and overwrite is False.
    """
    # Overwrite protection: stop if a split already exists, unless asked to replace it.
    existing_files = [path for path in (train_path, test_path) if path.exists()]
    if existing_files and not overwrite:
        raise FileExistsError(
            f"Split files already exist: {[str(path) for path in existing_files]}. "
            "The test set must stay the same. Use --overwrite only if you are sure."
        )

    # Save each set. mkdir creates the folder if it is missing.
    # index=False stops pandas adding an extra column of row numbers.
    for split_df, path in ((train_df, train_path), (test_df, test_path)):
        path.parent.mkdir(parents=True, exist_ok=True)
        split_df.to_csv(path, index=False, encoding="utf-8")


# The share of customers who churned, e.g. 0.288 means 28.8%.
# Trick: the average of True/False values is the share that are True.
def churn_rate(df: pd.DataFrame) -> float:
    """Return the share of customers who churned (0 to 1)."""
    return (df[TARGET_COLUMN] == POSITIVE_LABEL).mean()


# Run everything in order: load -> split -> save -> show a summary.
def main(overwrite: bool = False) -> None:
    """Load the raw data, split it, save both sets and log a summary."""
    raw_df = load_raw_data()
    train_df, test_df = split_train_test(raw_df)
    save_splits(train_df, test_df, overwrite=overwrite)

    # Show rows and churn rate for each set, to prove stratification worked.
    for name, split_df in (("raw", raw_df), ("train", train_df), ("test", test_df)):
        logger.info(
            "%-5s rows: %6d | churn rate: %.2f%%",
            name,
            len(split_df),
            churn_rate(split_df) * 100,
        )
    logger.info("Saved train to %s and test to %s", TRAIN_PATH, TEST_PATH)


# Runs only when this file is run directly (python -m churn.split),
# not when another file (like a test) imports it.
if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    # argparse adds the --overwrite option and the --help text.
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace existing split files.",
    )
    main(overwrite=parser.parse_args().overwrite)
